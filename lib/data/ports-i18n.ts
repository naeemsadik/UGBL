/**
 * Merges Bengali text overlays onto the English port data.
 * Technical values (drafts, coordinates, LOA numbers) are preserved from English.
 */
export function getTranslatedPortData<T extends {
  slug: string;
  title: string;
  subtitle: string;
  overviewTitle: string;
  overview: string;
  facts: { label: string; value: string; description: string }[];
  mapTitle: string;
  mapDescription: string;
  notesTitle: string;
  notes: string[];
  ctaTitle: string;
  ctaText: string;
  ctaLabel: string;
  flatCoreSections?: { title?: string; paragraphs: string[]; items?: { label: string; detail: string }[] }[];
  technicalSections?: { title?: string; items: { label: string; value: string; description?: string }[] }[];
  berthRestrictions?: { title?: string; items: { name: string; maxLOA?: string; maxDraft?: string; details?: string }[] };
}>(
  englishData: T,
  locale: string
): T {
  if (locale !== "BN") return englishData;

  const overlay = portsBn[englishData.slug];
  if (!overlay) return englishData;

  const translated = { ...englishData };

  // Simple string overrides
  if (overlay.title) translated.title = overlay.title;
  if (overlay.subtitle) translated.subtitle = overlay.subtitle;
  if (overlay.overviewTitle) translated.overviewTitle = overlay.overviewTitle;
  if (overlay.overview) translated.overview = overlay.overview;
  if (overlay.mapTitle) translated.mapTitle = overlay.mapTitle;
  if (overlay.mapDescription) translated.mapDescription = overlay.mapDescription;
  if (overlay.notesTitle) translated.notesTitle = overlay.notesTitle;
  if (overlay.ctaTitle) translated.ctaTitle = overlay.ctaTitle;
  if (overlay.ctaText) translated.ctaText = overlay.ctaText;
  if (overlay.ctaLabel) translated.ctaLabel = overlay.ctaLabel;

  // Facts: keep technical values, translate labels & descriptions
  if (overlay.facts && englishData.facts) {
    translated.facts = englishData.facts.map((fact, i) => ({
      ...fact,
      label: overlay.facts![i]?.label ?? fact.label,
      description: overlay.facts![i]?.description ?? fact.description,
    }));
  }

  // Notes
  if (overlay.notes) translated.notes = overlay.notes;

  // Flat core sections
  if (overlay.flatCoreSections) {
    translated.flatCoreSections = overlay.flatCoreSections;
  }

  // Technical sections
  if (overlay.technicalSections) {
    (translated as any).technicalSections = overlay.technicalSections;
  }

  // Berth restrictions
  if (overlay.berthRestrictions) {
    (translated as any).berthRestrictions = overlay.berthRestrictions;
  }

  return translated;
}

